// Host-level render check. The unit tests prove what the plugin maps; this
// proves the snapshot CodexBar's real validator accepts and renders it.
//
// It writes a stub provider that returns the snapshot opendesign.js builds from
// recorded payloads — same id, origins, auth and settings, so an approval
// already granted to the plugin also covers the stub. Then:
//
//   node test/harness/render-check.mjs ~/.config/codexbar/providers session
//   codexbar plugins fetch opendesign
//
// The stub is not the plugin: it has no fetchUsage of its own, so the fetch
// needs no network.

import { writeFileSync } from "node:fs";
import { join } from "node:path";

import { PREFLIGHT, PROFILE, SUMMARY, host, loadPlugin, ok } from "../host.mjs";

const [directory, scenario = "session"] = process.argv.slice(2);
if (!directory) {
  console.error("usage: node test/harness/render-check.mjs <providers-dir> [session|windows|wallet]");
  process.exit(2);
}

const THIRD_WINDOW = {
  balanceUsd: "1.5000",
  codingPlan: {
    eligible: true,
    tier: "go",
    windows: [
      { policyId: "monthly", durationSeconds: 2592000, usedCredits: "16251", limitCredits: "150000" },
      { policyId: "session", durationSeconds: 18000, usedCredits: "16251", limitCredits: "50000" },
      { policyId: "weekly", durationSeconds: 604800, usedCredits: "16251", limitCredits: "150000" },
    ],
  },
};
const WALLET_ONLY = {
  balanceUsd: "12.3456",
  funding: "wallet",
  codingPlan: { eligible: false, tier: "go", windows: [] },
};

const fixtures = {
  session: { preflight: PREFLIGHT, summary: SUMMARY },
  windows: { preflight: THIRD_WINDOW, summary: SUMMARY },
  wallet: { preflight: WALLET_ONLY, summary: SUMMARY },
}[scenario];
if (!fixtures) {
  console.error("unknown scenario: " + scenario);
  process.exit(2);
}

const definition = loadPlugin();
const { ctx } = host({
  "/workspaces/current": ok(PROFILE),
  "/workspaces/ws1/billing/preflight": ok(fixtures.preflight),
  "/billing/summary": ok(fixtures.summary),
});
const snapshot = await definition.fetchUsage(ctx);

const stub = `// Generated by test/harness/render-check.mjs (${scenario}) from recorded
// control-plane payloads. Returns the snapshot opendesign.js builds; it is not
// the plugin itself.
defineProvider({
  id: ${JSON.stringify(definition.id)},
  name: ${JSON.stringify(definition.name)},
  icon: ${JSON.stringify(definition.icon)},
  endpoints: ${JSON.stringify(definition.endpoints)},
  auth: ${JSON.stringify(definition.auth)},
  capabilities: ${JSON.stringify(definition.capabilities)},
  settings: ${JSON.stringify(definition.settings)},
  async fetchUsage() {
    return ${JSON.stringify(snapshot, null, 2)};
  },
});
`;

const target = join(directory, "opendesign.js");
writeFileSync(target, stub);
console.log("wrote " + target);
console.log(JSON.stringify(snapshot, null, 2));
